#!/bin/sh
# Builds and runs tests/wall_tests.c on a PC (Linux/WSL, needs gcc and nm).
#
#   GINT_INCLUDE=<dir containing gint/> tests/run_wall_tests.sh
#
# GINT_INCLUDE defaults to the fxSDK sysroot. Only gint's headers are used:
# every gint/OS function the game calls is replaced by a generated stub, and
# the storage memory by an in-memory filesystem (in wall_tests.c).
set -e
cd "$(dirname "$0")/.."

if [ -z "$GINT_INCLUDE" ]; then
	GINT_INCLUDE="$(ls -d "$HOME"/.local/share/fxsdk/sysroot/sh3eb-elf/include 2>/dev/null | head -n1)"
fi
if [ ! -f "$GINT_INCLUDE/gint/display.h" ]; then
	echo "Set GINT_INCLUDE to the directory that contains gint/display.h" >&2
	exit 1
fi

OUT=build-tests
rm -rf "$OUT"; mkdir -p "$OUT/fake/fxlibc" "$OUT/fake/gint"
printf '#pragma once\nvoid __printf_enable_fixed(void);\n' > "$OUT/fake/fxlibc/printf.h"
# config.h is generated by gint's build; a source checkout only has the template
if [ ! -f "$GINT_INCLUDE/gint/config.h" ]; then
	sed 's/@GINT_GIT_VERSION@/0/; s/@GINT_GIT_HASH@/0/; s/#cmakedefine.*//' "$GINT_INCLUDE/gint/config.h.in" > "$OUT/fake/gint/config.h"
fi

CFLAGS="-std=gnu11 -O1 -g -D FX9860G -w -I include -I $OUT/fake -I $GINT_INCLUDE"
# The whole game except main.c (whose globals the test defines) and the
# assembler optimiser
SOURCES="$(ls src/*.c | grep -v -e 'src/main.c' -e 'src/optimise.c')"
for f in $SOURCES tests/wall_tests.c; do
	gcc $CFLAGS -c "$f" -o "$OUT/$(basename "$f").o"
done

# Generate stubs for everything that is still undefined and isn't provided
# by the C library: images/fonts become zeroed objects, functions return 0
nm -u "$OUT"/*.o | awk 'NF == 2 {print $2}' | sort -u > "$OUT/undef"
nm --defined-only "$OUT"/*.o | awk 'NF == 3 {print $3}' | sort -u > "$OUT/def"
comm -23 "$OUT/undef" "$OUT/def" > "$OUT/missing"
{
	echo '/* Generated by run_wall_tests.sh */'
	while read -r sym; do
		case "$sym" in
			img_*|font_*) echo "char $sym[64];" ;;
			gint) echo "unsigned int gint[32];" ;;
			_GLOBAL_OFFSET_TABLE_|__stack_chk_fail|__*_chk) ;;
			malloc|calloc|realloc|free|memcpy|memmove|memset|memcmp|strlen|strcmp|strncmp|strncpy|strcpy|strchr|\
			snprintf|sprintf|printf|puts|rand|srand|abs|exit|round|roundf|ceil|ceilf|floor|floorf|modf|pow|powf|sin|cos|\
			sinf|cosf|sincos|sqrt|sqrtf|fabs|fabsf|atan2|atan2f|lroundf|fmod|fmodf|putchar|fwrite|fopen|fclose|fprintf) ;;
			*) echo "long $sym() { return 0; }" ;;
		esac
	done < "$OUT/missing"
} > "$OUT/stubs.c"
gcc -std=gnu11 -w -c "$OUT/stubs.c" -o "$OUT/stubs.o"
gcc -g -o "$OUT/wall_tests" "$OUT"/*.o -lm
"$OUT/wall_tests"
